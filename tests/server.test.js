import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { WebSocket } from 'ws';
const port = 19187;
const token = 'test-mobile-token-01234567890123456789';
const deviceToken = 'test-device-token-01234567890123456789';
const key = 'test-signing-key-01234567890123456789';
const base = `http://127.0.0.1:${port}`;

test('authenticated commands, acknowledgements, telemetry and private files', async t => {
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'doorbell-test-'));
  const child = spawn(process.execPath, ['server.js'], { cwd: new URL('..', import.meta.url), env: {...process.env, HOST:'127.0.0.1', PORT:String(port), DATA_DIR:dataDir, OWNER_PIN:'987654', DEVICE_HMAC_KEY:key, DEVICE_CONNECTION_TOKEN:deviceToken, MOBILE_WS_TOKEN:token}, stdio:['ignore','pipe','pipe'] });
  let logs = ''; child.stdout.on('data', b => logs += b); child.stderr.on('data', b => logs += b);
  t.after(() => child.kill());
  for (let i=0;i<100;i++) { try { await fetch(base); break; } catch { await new Promise(r=>setTimeout(r,100)); } }
  assert.equal(child.exitCode, null, logs);
  for (const route of ['/status','/api/access_history','/api/unlock','/api/diagnostics','/api/cards','/api/device_settings']) assert.equal((await fetch(base+route)).status,401);
  for (const route of ['/.env','/server.js','/package.json','/firmware/esp32_cam_doorbell/include/secrets.h']) assert.equal((await fetch(base+route)).status,404);
  const headers = {Authorization:`Bearer ${token}`, 'Content-Type':'application/json'};
  const post = (route, body) => fetch(base+route,{method:'POST',headers,body:JSON.stringify(body)});
  assert.equal((await post('/api/unlock',{username:'__proto__',pin:'987654'})).status,401);
  const device = new WebSocket(`ws://127.0.0.1:${port}/ws?device_token=${deviceToken}`);
  await once(device,'open'); t.after(()=>device.close());
  const bootId='a'.repeat(32);
  device.send(JSON.stringify({type:'esp32_connect',bootId,lastSequence:0}));
  await new Promise(r=>setTimeout(r,30));
  let sequence=0, received=[];
  device.on('message',(raw,isBinary)=> {
    if(isBinary) return;
    const envelope=JSON.parse(raw);
    if(!envelope.payload) return;
    assert.equal(envelope.signature,crypto.createHmac('sha256',key).update(envelope.payload).digest('hex'));
    const command=JSON.parse(envelope.payload);
    assert.equal(command.bootId,bootId); assert.ok(command.seq>sequence); sequence=command.seq;
    received.push(command);
    if(command.command==='get_cards') device.send(JSON.stringify({type:'cards_snapshot',nonce:command.nonce,cards:[{uid:'F909F41F',name:'White card',userId:'owner',permission:'gate_access',active:true}]}));
    // Prove HTTP waits for device confirmation, and propagate failed device writes.
    setTimeout(()=>device.send(JSON.stringify({type:'command_result',nonce:command.nonce,success:command.command!=='cards_enabled'||command.enabled===false})),100);
  });
  const started=Date.now();
  assert.equal((await post('/api/unlock',{username:'owner',pin:'987654'})).status,200);
  assert.ok(Date.now()-started>=90);
  assert.equal((await post('/api/cards_enabled',{username:'owner',pin:'987654',enabled:false})).status,200);
  assert.equal((await post('/api/cards_enabled',{username:'owner',pin:'987654',enabled:true})).status,503);
  assert.equal(received[1].enabled,false);
  device.send(JSON.stringify({type:'heartbeat',cardsEnabled:false,relayFault:false,gateLock:'locked',rssi:-60}));
  await new Promise(r=>setTimeout(r,30));
  const status=await (await fetch(base+'/status',{headers})).json();
  assert.equal(status.cardsEnabled,false); assert.equal(status.relayFault,false);
  assert.equal((await fetch(base+'/api/cards',{headers})).status,409);
  const settings={version:1,idleBrightness:8,activeBrightness:120,speakerGain:4};
  device.send(JSON.stringify({type:'heartbeat',cardsEnabled:false,relayFault:false,settings,uptimeSec:120,freeHeap:50000}));
  await new Promise(r=>setTimeout(r,30));
  assert.equal((await post('/api/device_settings',{username:'owner',pin:'987654',settings:{...settings,speakerGain:7}})).status,400);
  assert.equal((await post('/api/device_settings',{username:'owner',pin:'123456',settings})).status,403);
  assert.equal((await post('/api/device_settings',{username:'owner',pin:'987654',settings:{...settings,command:'unlock',nonce:'attacker'}})).status,200);
  assert.equal(received.at(-1).command,'device_settings');assert.notEqual(received.at(-1).nonce,'attacker');
  const cards=await(await fetch(base+'/api/cards',{headers})).json();assert.equal(cards.cards[0].uid,'F909F41F');
  const diagnostics=await(await fetch(base+'/api/diagnostics',{headers})).json();assert.equal(diagnostics.telemetry.freeHeap,50000);assert.ok(diagnostics.commands.some(item=>item.action==='device_settings'&&item.result==='confirmed'));assert.ok(!JSON.stringify(diagnostics).includes(key));
  assert.equal((await post('/api/sync_cards',{username:'owner',pin:'987654',cards:[{uid:'F909F41F'}]})).status,400);
  const media=new WebSocket(`ws://127.0.0.1:${port}/api/media?token=${token}`);
  await once(media,'open'); t.after(()=>media.close());
  const jpeg=Buffer.from([1,255,216,255,217]);
  const mediaReceived=once(media,'message'); device.send(jpeg);
  assert.deepEqual((await mediaReceived)[0],jpeg);
  const pcm=Buffer.alloc(641); pcm[0]=2;
  const audioReceived=once(device,'message'); media.send(pcm);
  assert.deepEqual((await audioReceived)[0],pcm);
  const event={eventId:'offline-unique-test',type:'nfc_access',timestamp:1234};
  device.send(JSON.stringify({type:'offline_sync_batch',events:[event,event]}));
  await new Promise(r=>setTimeout(r,100));
  const saved=JSON.parse(fs.readFileSync(path.join(dataDir,'history.json'),'utf8'));
  assert.equal(saved.access.filter(item=>item.eventId===event.eventId).length,1);
  assert.ok(received.some(command=>command.command==='offline_ack'&&command.eventIds.includes(event.eventId)));
  media.close(); await once(media,'close');
  device.close(); await once(device,'close');
  await new Promise(r=>setTimeout(r,30));
  assert.equal((await (await fetch(base+'/status',{headers})).json()).status,'offline');
});
